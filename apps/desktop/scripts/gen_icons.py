#!/usr/bin/env python3
"""Converts the Tauri app's inline Lucide icon set (src/components/Icon.tsx) into C# path data.
Usage: gen_icons.py <Icon.tsx> <out.cs>. Lucide is ISC-licensed (https://lucide.dev/license)."""
import re, sys

src = open(sys.argv[1]).read()
start = src.index('const PATHS')
body = src[start:src.index('export type IconName')]

def attrs(s):
    return {m.group(1): m.group(2) for m in re.finditer(r'([A-Za-z0-9]+)="([^"]*)"', s)}

def f(v):
    v = float(v)
    return str(int(v)) if v == int(v) else ('%g' % v)

def conv(tag, a):
    g = lambda k, d='0': float(a.get(k, d))
    if tag == 'path': return a['d']
    if tag == 'line': return f"M{f(g('x1'))} {f(g('y1'))}L{f(g('x2'))} {f(g('y2'))}"
    if tag in ('polyline', 'polygon'):
        pts = [float(x) for x in re.split(r'[\s,]+', a['points'].strip())]
        pairs = list(zip(pts[0::2], pts[1::2]))
        d = 'M' + 'L'.join(f"{f(x)} {f(y)}" for x, y in pairs)
        return d + ('Z' if tag == 'polygon' else '')
    if tag == 'circle':
        cx, cy, r = g('cx'), g('cy'), g('r')
        return f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0Z"
    if tag == 'ellipse':
        cx, cy, rx, ry = g('cx'), g('cy'), g('rx'), g('ry')
        return f"M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0Z"
    if tag == 'rect':
        x, y, w, h = g('x'), g('y'), g('width'), g('height')
        rx = float(a['rx']) if 'rx' in a else (float(a['ry']) if 'ry' in a else 0)
        if rx == 0: return f"M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
        return (f"M{f(x + rx)} {f(y)}h{f(w - 2 * rx)}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(rx)}v{f(h - 2 * rx)}"
                f"a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(rx)}h{f(-(w - 2 * rx))}a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(-rx)}"
                f"v{f(-(h - 2 * rx))}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(-rx)}Z")
    raise SystemExit('unknown tag ' + tag)

icons = {}
for m in re.finditer(r'^\s{2}(?:"([^"]+)"|([A-Za-z0-9_]+)):\s*\(\s*(?:<>)?(.*?)(?:</>)?\s*\),', body, re.S | re.M):
    name = m.group(1) or m.group(2)
    parts = []
    for e in re.finditer(r'<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*?)/>', m.group(3), re.S):
        parts.append(conv(e.group(1), attrs(e.group(2))))
    icons[name] = '|'.join(parts)   # one sub-path per element: a leading relative 'm' must stay relative to its own start

for m in re.finditer(r'^\s{2}(?:"([^"]+)"|([A-Za-z0-9_]+)):\s*(<(?:path|line|polyline|polygon|circle|ellipse|rect)\b[^>]*?/>)\s*,', body, re.S | re.M):
    name = m.group(1) or m.group(2)
    t = re.match(r'<(\w+)\b([^>]*?)/>', m.group(3), re.S)
    icons[name] = conv(t.group(1), attrs(t.group(2)))

out = ['// <auto-generated> from the Tauri app\'s Icon.tsx by scripts/gen_icons.py — Lucide geometry (ISC), 24x24 box, 2px stroke.',
       'namespace CraftPanel.App.Controls;', '', 'public static class IconData', '{',
       '    public static readonly Dictionary<string, string> Paths = new()', '    {']
for k in sorted(icons):
    out.append(f'        ["{k}"] = "{icons[k]}",')
out += ['    };', '}', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print(len(icons), 'icons')
